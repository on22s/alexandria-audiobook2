def voices_for(category, description='Old synthetic label', member_category='custom'):
    if category == 'ensemble':
        return {'A': {'type': 'ensemble', 'members': ['M'], 'description': description},
                'M': {'type': member_category, 'voice': 'Ryan', 'seed': 1,
                      'description': 'Synthetic member label'}}
    entry = {'type': category, 'voice': 'Ryan', 'seed': 42, 'description': description,
             'character_style': 'calm', 'default_style': 'quiet'}
    if category == 'clone':
        entry.update(ref_audio='synthetic-ref.wav', ref_text='Synthetic reference words')
    if category in ('lora', 'builtin_lora'):
        entry.update(adapter_path='synthetic-adapter', adapter_generation_sha256='a' * 64)
    return {'A': entry}


def identity_snapshot(voices, chunk=CHUNK):
    speaker = chunk.get('speaker')
    _, effective, _ = get_chunk_render_voice_selection(voices, speaker, chunk, 0)
    selected = effective[tts.get_resolved_speaker(speaker, effective)]
    context = get_pronunciation_render_context(voices, chunk, 0, SETTINGS)
    return {
        'inputs': get_chunk_voice_inputs(voices, chunk, 0),
        'pronunciation': context['voice_sha256'],
        'take': get_receipt_voice_digest(3, selected, selected.get('seed')),
    }


def changed_fields(before, after):
    return {key for key in before if before[key] != after[key]}


class InertDescriptionIdentityTests(unittest.TestCase):
    def test_description_through_a_narrator_inside_an_ensemble(self):
        # The group reaches Narrator, whose own entry is absent, so the row
        # settles it on the configured NARRATOR fallback (#2170 ensembles).
        def snapshot(kind, description, chapter=None):
            chosen = {'type': kind, 'voice': 'Ryan', 'seed': 7, 'description': description}
            narrator = ({'alias_of': 'D'} if chapter is None else
                        {'type': 'custom', 'voice': 'Serena', 'seed': 3,
                         'narrator_strategy': 'chapter', 'versions': {'v': chosen}})
            voices = {'A': {'type': 'ensemble', 'members': ['B', 'Narrator'], 'description': 'group'},
                      'B': {'type': 'custom', 'voice': 'Aiden', 'seed': 5},
                      'NARRATOR': narrator, 'D': chosen}
            chunk = dict(CHUNK, **({} if chapter is None else {'narrator_version': chapter}))
            inputs = get_chunk_voice_inputs(voices, chunk, 0)
            raw = get_chunk_voice_inputs(voices, chunk, 0, canonical=False)
            context = get_pronunciation_render_context(voices, chunk, 0, SETTINGS)
            self.assertTrue(any(value.get('type') == kind and value.get('voice') == 'Ryan'
                                for value in inputs.values()), inputs)
            return inputs, raw, context['voice_sha256']
        for chapter in (None, 'v'):
            for kind, inert in (('custom', True), ('clone', True), ('design', False)):
                with self.subTest(chapter=chapter, kind=kind):
                    before, after = snapshot(kind, 'Old', chapter), snapshot(kind, 'New', chapter)
                    self.assertEqual(inert, before[0] == after[0])
                    self.assertEqual(inert, before[2] == after[2])
                    self.assertNotEqual(before[1], after[1])

    def test_description_only_edit_is_inert_for_every_non_design_voice(self):
        for category in ('custom', 'clone', 'lora', 'builtin_lora', 'ensemble'):
            with self.subTest(category=category):
                old = voices_for(category, 'Old synthetic label')
                new = voices_for(category, 'New synthetic label')
                before, after = identity_snapshot(old), identity_snapshot(new)
                self.assertEqual(before, after)
                for entry in old.values():
                    if tts.voice_category(entry) != 'design':
                        self.assertIsNone(tts.get_voice_render_identity(entry)['description'])

    def test_description_only_edit_still_changes_every_design_voice(self):
        old = {'A': {'type': 'design', 'seed': 7, 'description': 'Deep synthetic voice'}}
        new = {'A': {'type': 'design', 'seed': 7, 'description': 'Bright synthetic voice'}}
        self.assertEqual(changed_fields(identity_snapshot(old), identity_snapshot(new)),
                         {'inputs', 'pronunciation', 'take'})

    def test_ensemble_with_a_design_member_still_invalidates(self):
        old = voices_for('ensemble', 'Group label', member_category='design')
        new = copy.deepcopy(old)
        new['M']['description'] = 'Different designed member'
        self.assertEqual(changed_fields(identity_snapshot(old), identity_snapshot(new)),
                         {'inputs', 'pronunciation'})
        # The group's own description stays inert.
        relabelled = copy.deepcopy(old)
        relabelled['A']['description'] = 'Another group label'
        self.assertEqual(identity_snapshot(old), identity_snapshot(relabelled))

    def test_alias_label_is_inert_but_an_alias_to_design_still_invalidates(self):
        old = {'A': {'alias_of': 'B', 'description': 'Old alias label'},
               'B': {'type': 'design', 'seed': 3, 'description': 'Old instruction'}}
        relabelled = copy.deepcopy(old)
        relabelled['A']['description'] = 'New alias label'
        self.assertEqual(identity_snapshot(old), identity_snapshot(relabelled))
        redescribed = copy.deepcopy(old)
        redescribed['B']['description'] = 'New instruction'
        self.assertEqual(changed_fields(identity_snapshot(old), identity_snapshot(redescribed)),
                         {'inputs', 'pronunciation', 'take'})

    def test_version_timeline_description_follows_the_effective_category(self):
        for base_type, expected in (('custom', set()), ('design', {'inputs', 'pronunciation', 'take'})):
            with self.subTest(base_type=base_type):
                old = {'A': {'type': base_type, 'voice': 'Ryan', 'seed': 5,
                             'description': 'Base label',
                             'versions': {'v2': {'description': 'Old version label'}},
                             'version_timeline': [{'from_index': 0, 'version_id': 'v2'}]}}
                new = copy.deepcopy(old)
                new['A']['versions']['v2']['description'] = 'New version label'
                self.assertEqual(changed_fields(identity_snapshot(old), identity_snapshot(new)),
                                 expected)

    def test_narrator_strategy_follows_the_selected_category(self):
        chunk = {'uid': 'narrator-line', 'speaker': 'NARRATOR', 'text': 'Synthetic line.',
                 'focus_speaker': 'A'}
        for focus_type, expected in (('custom', set()), ('design', {'inputs', 'pronunciation', 'take'})):
            with self.subTest(focus_type=focus_type):
                voices = {'NARRATOR': {'type': 'custom', 'voice': 'Ryan', 'seed': 2,
                                       'narrator_strategy': 'focus',
                                       'description': 'Narrator label'},
                          'A': {'type': focus_type, 'voice': 'Aiden', 'seed': 1,
                                'description': 'Old focus label'}}
                edited = copy.deepcopy(voices)
                edited['A']['description'] = 'New focus label'
                self.assertEqual(changed_fields(identity_snapshot(voices, chunk),
                                                identity_snapshot(edited, chunk)), expected)

    def test_any_other_field_or_a_type_change_still_invalidates(self):
        def mutate(category, voices):
            if category == 'custom':
                voices['A']['voice'] = 'Jenny'
            elif category == 'clone':
                voices['A']['ref_audio'] = 'another-ref.wav'
            elif category in ('lora', 'builtin_lora'):
                voices['A']['adapter_generation_sha256'] = 'b' * 64
            elif category == 'design':
                voices['A']['seed'] = 43
            else:
                voices['M']['voice'] = 'Jenny'
        for category in ('custom', 'clone', 'lora', 'builtin_lora', 'design', 'ensemble'):
            with self.subTest(category=category):
                old = voices_for(category)
                edited = copy.deepcopy(old)
                mutate(category, edited)
                self.assertTrue(changed_fields(identity_snapshot(old), identity_snapshot(edited)))
        for old_type, new_type in (('custom', 'design'), ('design', 'custom')):
            with self.subTest(type_change=(old_type, new_type)):
                old = voices_for(old_type, 'Same label')
                new = copy.deepcopy(old)
                new['A']['type'] = new_type
                self.assertEqual(changed_fields(identity_snapshot(old), identity_snapshot(new)),
                                 {'inputs', 'pronunciation', 'take'})

    def test_description_edit_keeps_done_chunk_and_export_current(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            manager = ProjectManager(str(root))
            audio = root / 'voicelines' / 'done.wav'
            audio.parent.mkdir(parents=True, exist_ok=True)
            audio.write_bytes(b'synthetic audio sentinel')
            rows = [{'id': 0, 'uid': 'u0', 'speaker': 'A', 'text': 'Synthetic line.',
                     'status': 'done', 'audio_path': 'voicelines/done.wav'}]
            manager.save_chunks(rows)
            export_before = _get_rows_digest(manager.get_saved_chunks())
            before = voices_for('custom', 'Old label')
            after = voices_for('custom', 'New label')
            manager._apply_voice_timeline_audio_invalidation_locked(before, after)
            saved = manager.get_saved_chunks()
            self.assertEqual('done', saved[0]['status'])
            self.assertEqual('voicelines/done.wav', saved[0]['audio_path'])
            self.assertEqual(b'synthetic audio sentinel', audio.read_bytes())
            self.assertEqual(export_before, _get_rows_digest(saved))

            design_before = voices_for('design', 'Old instruction')
            design_after = voices_for('design', 'New instruction')
            manager._apply_voice_timeline_audio_invalidation_locked(design_before, design_after)
            invalidated = manager.get_saved_chunks()
            self.assertEqual('pending', invalidated[0]['status'])
            self.assertIsNone(invalidated[0]['audio_path'])
            self.assertEqual(b'synthetic audio sentinel', audio.read_bytes())

