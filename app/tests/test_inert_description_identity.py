"""A description only affects renders whose backend reads it (#2170).

`description` is the VoiceDesign instruction. Custom, clone, LoRA and ensemble
renders never receive it, so a description-only edit must not invalidate
finished audio, drop scoped pronunciation rules or change a saved take's voice
digest. The legacy fixtures were generated by main's own code (recorded in the
fixture's `generated_by`) and pin the pre-fix digests this release still reads.
"""
