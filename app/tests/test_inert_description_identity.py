    @unittest.skipUnless(is_synthesis_workspace_supported(),
                         'Registered restore staging requires durable directory storage')
    def test_legacy_v3_take_digest_authorizes_only_the_unchanged_entry(self):
        from audio_take_history import AudioTakeHistory
        from take_publication import KEY, get_legacy_v3_voice_digest
        from take_restoration import capture_restore_target, restore_editor_take
        from tests.test_take_restoration import TakeRestorationTests
        fixture = TakeRestorationTests()

        def describe(manager, description):
            path = Path(manager.voice_config_path)
            voices = json.loads(path.read_text())
            voices['NARRATOR']['description'] = description
            path.write_text(json.dumps(voices))
            manager.invalidate_config_cache()
            return manager.get_voice_config_for_update()['NARRATOR']

        def install(root, saved, digest):
            history = AudioTakeHistory(root)
            with history._locked() as document:
                record = next(row for row in document['records']
                              if row['version'] == saved['version'])
                record['captured'][KEY]['dependencies']['voice_sha256'] = digest
                history._save(document)

        scenarios = ('unchanged', 'edited', 'tampered', 'other-entry')
        for scenario in scenarios:
            with self.subTest(scenario=scenario), fixture.prepared() as (
                    root, manager, engine, request, origin, original, current, displaced, saved):
                selected = describe(manager, 'A synthetic legacy description')
                seed = saved['captured'][KEY]['seed']
                if scenario == 'tampered':
                    install(root, saved, 'f' * 64)
                elif scenario == 'other-entry':
                    install(root, saved, get_legacy_v3_voice_digest(
                        {**selected, 'voice': 'Jenny'}, seed))
                else:
                    install(root, saved, get_legacy_v3_voice_digest(selected, seed))
                if scenario == 'edited':
                    describe(manager, 'A different legacy description')
                if scenario == 'unchanged':
                    restored = restore_editor_take(
                        manager, 0, request, capture_restore_target(manager, 0, request))
                    self.assertEqual((root / restored['audio_path']).read_bytes(), original)
                else:
                    with self.assertRaisesRegex(ValueError, 'voice or seed selection'):
                        restore_editor_take(
                            manager, 0, request, capture_restore_target(manager, 0, request))
                    self.assertEqual((root / current['audio_path']).read_bytes(), displaced)


