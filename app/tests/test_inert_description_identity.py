    def test_legacy_pronunciation_scope_still_applies_until_a_description_edit(self):
        case = FIXTURE['cases']['custom']
        legacy_digest = case['pronunciation_context']['voice_sha256']
        for description, applies in (('Warm synthetic narrator', True), ('Edited label', False)):
            with self.subTest(description=description):
                voices = copy.deepcopy(case['voices'])
                voices['A']['description'] = description
                context = get_pronunciation_render_context(voices, CHUNK, 0, SETTINGS)
                row = {'uid': CHUNK['uid'], 'text': 'Ann Ann',
                       'pronunciation_rules': [rule(uid=CHUNK['uid'], replacement='Ann Ann',
                                                    restrictions={'voice_sha256': legacy_digest})]}
                with ensure_occurrence_pronunciation_context(row, context):
                    result = ensure_speech_pronunciation_result(
                        get_prelexicon_speech_normalization('Ann Ann')['text'])
                self.assertEqual(applies, result['decisions'][0]['applied'])

    def test_canonical_pronunciation_scope_survives_a_description_edit(self):
        voices = voices_for('custom', 'Old label')
        context = get_pronunciation_render_context(voices, CHUNK, 0, SETTINGS)
        rule_data = rule(uid=CHUNK['uid'], replacement='Ann Ann',
                         restrictions={'voice_sha256': context['voice_sha256']})
        edited = voices_for('custom', 'New label')
        edited_context = get_pronunciation_render_context(edited, CHUNK, 0, SETTINGS)
        self.assertEqual(context['voice_sha256'], edited_context['voice_sha256'])
        row = {'uid': CHUNK['uid'], 'text': 'Ann Ann', 'pronunciation_rules': [rule_data]}
        with ensure_occurrence_pronunciation_context(row, edited_context):
            result = ensure_speech_pronunciation_result(
                get_prelexicon_speech_normalization('Ann Ann')['text'])
        self.assertTrue(result['decisions'][0]['applied'])

    def test_random_ordinary_configs_keep_their_identity(self):
        rng = random.Random(2170)
        categories = ('custom', 'clone', 'lora', 'builtin_lora', 'design', 'ensemble')
        voice_names = ('Ryan', 'Aiden', 'Jenny', 'Serena', 'Vivian')
        for round_index in range(2000):
            category = categories[round_index % len(categories)]
            description = rng.choice(('', 'Warm synthetic label', '  spaced label  ',
                                      'Another synthetic label'))
            voices = voices_for(category, description)
            voices['A']['voice'] = rng.choice(voice_names)
            voices['A']['seed'] = rng.randrange(0, 2 ** 31)
            edited = copy.deepcopy(voices)
            edited['A']['description'] = description + ' edited'
            before, after = identity_snapshot(voices), identity_snapshot(edited)
            unchanged = before == identity_snapshot(copy.deepcopy(voices))
            self.assertTrue(unchanged, round_index)
            if category == 'design':
                self.assertNotEqual(before, after, round_index)
            else:
                self.assertEqual(before, after, round_index)

